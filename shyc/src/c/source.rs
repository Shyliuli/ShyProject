//! Translating a parsed unit back into C source.
//!
//! The preprocessor already inlined includes and the parser already expanded
//! compile-time calls, so the unit here is ordinary C plus ShyC sugar: inferred
//! locals (let) and trait/impl blocks. A let becomes an inferred C local, and an
//! impl block has no C form yet.

use crate::ast::{
    self, AssignOp, BinaryOp, Block, Declaration, Expr, ForInit, FunctionDecl, Initializer,
    InitializerKind, Item, MemberOp, PostfixOp, Stmt, TypeName, UnaryOp,
};
use crate::c::types::{declaration_text, declarator_text, specs_text};
use crate::source::Diagnostic;

/// Renders the whole unit as one C translation unit.
pub fn render(unit: &ast::TranslationUnit) -> Result<String, Diagnostic> {
    let mut output = String::from("/* Generated by shyc --emit=c. */\n\n");
    for item in &unit.items {
        match item {
            Item::Decl(declaration) => {
                output.push_str(&declaration_text(declaration));
                output.push_str("\n\n");
            }
            Item::Function(function) => {
                output.push_str(&function_text(function)?);
                output.push_str("\n\n");
            }
            // A trait lives only at compile time and has no C form.
            Item::Trait(_) => {}
            // Imports were resolved while preprocessing.
            Item::Use(_) => {}
            Item::Impl(block) => {
                return Err(Diagnostic::new(
                    block.span,
                    "impl blocks are not translated to C yet",
                ));
            }
        }
    }
    Ok(output)
}

fn function_text(function: &FunctionDecl) -> Result<String, Diagnostic> {
    let specs = specs_text(&function.specs);
    let declarator = declarator_text(&function.declarator);
    Ok(format!(
        "{specs} {declarator} {}",
        block_text(&function.body, 0)?
    ))
}

fn block_text(block: &Block, depth: usize) -> Result<String, Diagnostic> {
    let mut output = String::from("{\n");
    for statement in &block.stmts {
        output.push_str(&stmt_text(statement, depth + 1)?);
    }
    output.push_str(&"    ".repeat(depth));
    output.push('}');
    Ok(output)
}

fn stmt_text(statement: &Stmt, depth: usize) -> Result<String, Diagnostic> {
    let indent = "    ".repeat(depth);
    let mut output = String::new();
    match statement {
        Stmt::Empty(_) => output.push_str(&format!("{indent};\n")),
        Stmt::Expr { expr, .. } => {
            output.push_str(&format!("{indent}{};\n", expr_text(expr)?));
        }
        Stmt::Decl(declaration) => {
            output.push_str(&indent);
            output.push_str(&local_declaration_text(declaration)?);
            output.push('\n');
        }
        Stmt::Let(declaration) => {
            let qualifier = if declaration.is_mut {
                "__auto_type"
            } else {
                "const __auto_type"
            };
            output.push_str(&format!(
                "{indent}{qualifier} {} = {};\n",
                declaration.name.text,
                expr_text(&declaration.init)?
            ));
        }
        Stmt::Block(block) => {
            output.push_str(&indent);
            output.push_str(&block_text(block, depth)?);
            output.push('\n');
        }
        Stmt::If {
            condition,
            then_branch,
            else_branch,
            ..
        } => {
            output.push_str(&format!("{indent}if ({}) ", expr_text(condition)?));
            output.push_str(&stmt_text(then_branch, depth)?);
            if let Some(else_branch) = else_branch {
                output.pop();
                output.push_str(" else ");
                output.push_str(&stmt_text(else_branch, depth)?);
            }
            output.push('\n');
        }
        Stmt::While {
            condition, body, ..
        } => {
            output.push_str(&format!("{indent}while ({}) ", expr_text(condition)?));
            output.push_str(&stmt_text(body, depth)?);
            output.push('\n');
        }
        Stmt::DoWhile {
            body, condition, ..
        } => {
            output.push_str(&format!("{indent}do "));
            output.push_str(&stmt_text(body, depth)?);
            output.push_str(&format!(" while ({});\n", expr_text(condition)?));
        }
        Stmt::For {
            init,
            condition,
            step,
            body,
            ..
        } => {
            let init_text = match init.as_deref() {
                None => String::new(),
                Some(ForInit::Expr(expr)) => expr_text(expr)?,
                Some(ForInit::Decl(declaration)) => {
                    local_declaration_text(declaration)?.trim_end_matches(';').to_string()
                }
                Some(ForInit::Let(declaration)) => format!(
                    "__auto_type {} = {}",
                    declaration.name.text,
                    expr_text(&declaration.init)?
                ),
            };
            let condition_text = match condition.as_deref() {
                Some(condition) => expr_text(condition)?,
                None => String::new(),
            };
            let step_text = match step.as_deref() {
                Some(step) => expr_text(step)?,
                None => String::new(),
            };
            output.push_str(&format!(
                "{indent}for ({init_text}; {condition_text}; {step_text}) "
            ));
            output.push_str(&stmt_text(body, depth)?);
            output.push('\n');
        }
        Stmt::Switch {
            condition, body, ..
        } => {
            output.push_str(&format!("{indent}switch ({}) ", expr_text(condition)?));
            output.push_str(&stmt_text(body, depth)?);
            output.push('\n');
        }
        Stmt::Case {
            value, end, stmt, ..
        } => {
            output.push_str(&format!("{indent}case {}", expr_text(value)?));
            if let Some(end) = end {
                output.push_str(&format!(" ... {}", expr_text(end)?));
            }
            output.push_str(": ");
            output.push_str(stmt_text(stmt, depth)?.trim_start());
        }
        Stmt::Default { stmt, .. } => {
            output.push_str(&format!("{indent}default: "));
            output.push_str(stmt_text(stmt, depth)?.trim_start());
        }
        Stmt::Label { name, stmt, .. } => {
            output.push_str(&format!("{indent}{}: ", name.text));
            output.push_str(stmt_text(stmt, depth)?.trim_start());
        }
        Stmt::Goto { label, .. } => output.push_str(&format!("{indent}goto {};\n", label.text)),
        Stmt::Break(_) => output.push_str(&format!("{indent}break;\n")),
        Stmt::Continue(_) => output.push_str(&format!("{indent}continue;\n")),
        Stmt::Return { value, .. } => match value {
            Some(value) => output.push_str(&format!("{indent}return {};\n", expr_text(value)?)),
            None => output.push_str(&format!("{indent}return;\n")),
        },
        Stmt::Asm(asm) => {
            return Err(Diagnostic::new(asm.span(), "inline assembly has no C form"));
        }
    }
    Ok(output)
}

fn local_declaration_text(declaration: &Declaration) -> Result<String, Diagnostic> {
    let specs = specs_text(&declaration.specs);
    let mut declarators = String::new();
    for (index, declarator) in declaration.declarators.iter().enumerate() {
        if index > 0 {
            declarators.push_str(", ");
        }
        declarators.push_str(&declarator_text(&declarator.declarator));
        if let Some(init) = &declarator.init {
            declarators.push_str(" = ");
            declarators.push_str(&initializer_text(init)?);
        }
    }
    Ok(format!("{specs} {declarators};"))
}

fn initializer_text(initializer: &Initializer) -> Result<String, Diagnostic> {
    match &initializer.kind {
        InitializerKind::Expr(expr) => expr_text(expr),
        InitializerKind::List(entries) => {
            let mut output = String::from("{");
            for (index, entry) in entries.iter().enumerate() {
                if index > 0 {
                    output.push_str(", ");
                }
                for designator in &entry.designators {
                    match designator {
                        ast::Designator::Field(name) => {
                            output.push_str(&format!(".{} ", name.text));
                        }
                        ast::Designator::Index(expr) => {
                            output.push_str(&format!("[{}] ", expr_text(expr)?));
                        }
                    }
                }
                output.push_str(&initializer_text(&entry.value)?);
            }
            output.push('}');
            Ok(output)
        }
    }
}

fn expr_text(expr: &Expr) -> Result<String, Diagnostic> {
    match expr {
        Expr::Number(literal) => Ok(literal.text.clone()),
        Expr::Char(literal) => Ok(format!("'{}'", literal.raw)),
        Expr::String(group) => Ok(group
            .parts
            .iter()
            .map(|part| format!("{}\"{}\"", part.prefix, part.raw))
            .collect::<Vec<_>>()
            .join(" ")),
        Expr::Name(name) => Ok(name.text.clone()),
        Expr::Unary { op, operand, .. } => {
            Ok(format!("({}{})", unary_op_text(*op), expr_text(operand)?))
        }
        Expr::Postfix { op, operand, .. } => Ok(format!(
            "({}{})",
            expr_text(operand)?,
            match op {
                PostfixOp::Increment => "++",
                PostfixOp::Decrement => "--",
            }
        )),
        Expr::Binary {
            op, left, right, ..
        } => Ok(format!(
            "({} {} {})",
            expr_text(left)?,
            binary_op_text(*op),
            expr_text(right)?
        )),
        Expr::Assignment {
            op, left, right, ..
        } => Ok(format!(
            "({} {} {})",
            expr_text(left)?,
            assign_op_text(*op),
            expr_text(right)?
        )),
        Expr::Conditional {
            condition,
            then_expr,
            else_expr,
            ..
        } => Ok(format!(
            "({} ? {} : {})",
            expr_text(condition)?,
            expr_text(then_expr)?,
            expr_text(else_expr)?
        )),
        Expr::Comma { left, right, .. } => {
            Ok(format!("({}, {})", expr_text(left)?, expr_text(right)?))
        }
        Expr::Call {
            callee,
            args,
            type_args,
            span,
        } => {
            if !type_args.is_empty() {
                return Err(Diagnostic::new(
                    *span,
                    "a generic call has no C form; instantiate it first",
                ));
            }
            let arguments = args
                .iter()
                .map(expr_text)
                .collect::<Result<Vec<_>, Diagnostic>>()?
                .join(", ");
            Ok(format!("{}({})", expr_text(callee)?, arguments))
        }
        Expr::Index { array, index, .. } => {
            Ok(format!("({})[{}]", expr_text(array)?, expr_text(index)?))
        }
        Expr::Member {
            object, name, op, ..
        } => Ok(format!(
            "({}){}{}",
            expr_text(object)?,
            match op {
                MemberOp::Dot => ".",
                MemberOp::Arrow => "->",
            },
            name.text
        )),
        Expr::Cast {
            type_name, value, ..
        } => Ok(format!(
            "(({}){})",
            type_name_text(type_name),
            expr_text(value)?
        )),
        Expr::SizeofType { type_name, .. } => Ok(format!("sizeof({})", type_name_text(type_name))),
        Expr::SizeofExpr { value, .. } => Ok(format!("sizeof({})", expr_text(value)?)),
        Expr::AlignofType { type_name, .. } => {
            Ok(format!("_Alignof({})", type_name_text(type_name)))
        }
        Expr::AlignofExpr { value, .. } => Ok(format!("_Alignof({})", expr_text(value)?)),
        Expr::StatementExpr { block, .. } => Ok(format!("({{ {} }})", block_text(block, 0)?)),
        other => Err(Diagnostic::new(
            other.span(),
            "this expression has no C form yet",
        )),
    }
}

fn type_name_text(type_name: &TypeName) -> String {
    let specs = specs_text(&type_name.specs);
    match &type_name.declarator {
        Some(declarator) => format!("{specs} {}", declarator_text(declarator)),
        None => specs,
    }
}

fn unary_op_text(op: UnaryOp) -> &'static str {
    match op {
        UnaryOp::Plus => "+",
        UnaryOp::Minus => "-",
        UnaryOp::LogicalNot => "!",
        UnaryOp::BitNot => "~",
        UnaryOp::Dereference => "*",
        UnaryOp::AddressOf => "&",
        UnaryOp::PreIncrement => "++",
        UnaryOp::PreDecrement => "--",
    }
}

fn binary_op_text(op: BinaryOp) -> &'static str {
    match op {
        BinaryOp::Multiply => "*",
        BinaryOp::Divide => "/",
        BinaryOp::Remainder => "%",
        BinaryOp::Add => "+",
        BinaryOp::Subtract => "-",
        BinaryOp::ShiftLeft => "<<",
        BinaryOp::ShiftRight => ">>",
        BinaryOp::Less => "<",
        BinaryOp::LessEqual => "<=",
        BinaryOp::Greater => ">",
        BinaryOp::GreaterEqual => ">=",
        BinaryOp::Equal => "==",
        BinaryOp::NotEqual => "!=",
        BinaryOp::BitAnd => "&",
        BinaryOp::BitXor => "^",
        BinaryOp::BitOr => "|",
        BinaryOp::LogicalAnd => "&&",
        BinaryOp::LogicalOr => "||",
    }
}

fn assign_op_text(op: AssignOp) -> &'static str {
    match op {
        AssignOp::Assign => "=",
        AssignOp::Add => "+=",
        AssignOp::Subtract => "-=",
        AssignOp::Multiply => "*=",
        AssignOp::Divide => "/=",
        AssignOp::Remainder => "%=",
        AssignOp::ShiftLeft => "<<=",
        AssignOp::ShiftRight => ">>=",
        AssignOp::BitAnd => "&=",
        AssignOp::BitXor => "^=",
        AssignOp::BitOr => "|=",
    }
}
