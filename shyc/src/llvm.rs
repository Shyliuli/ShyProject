fn emit_global(w: &mut Writer, global: &Global, options: &Options) -> Result<(), Diagnostic> {
    let keyword = if global.readonly {
        "constant"
    } else {
        "global"
    };
    let (llvm_ty, initializer) = if global.relocations.is_empty() {
        (
            format!("[{} x i8]", global.bytes.len()),
            byte_array(&global.bytes),
        )
    } else {
        relocation_initializer(global, options)?
    };
    // Compiler-generated constants (`.L.str.N` and friends) are private: two
    // translation units both define `.L.str.0`, and only private linkage keeps
    // them from colliding at link time.
    let linkage = if global.symbol.starts_with(".L.") {
        "private "
    } else {
        ""
    };
    let mut text = format!(
        "{} = {}{} {llvm_ty} {initializer}",
        symbol(&global.symbol),
        linkage,
        keyword
    );
    if global.align != 0 {
        text.push_str(&format!(", align {}", global.align));
    }
    w.line(text);
    Ok(())
}

/// A byte array constant, wrapped for readability when it is long.
fn byte_array(bytes: &[u8]) -> String {
    if bytes.is_empty() {
        return "zeroinitializer".to_string();
    }
    let values: Vec<String> = bytes.iter().map(|byte| format!("i8 {byte}")).collect();
    if values.len() <= 16 {
        return format!("[{}]", values.join(", "));
    }
    let mut text = String::from("[\n");
    for (index, chunk) in values.chunks(16).enumerate() {
        if index > 0 {
            text.push_str(",\n");
        }
        text.push_str("        ");
        text.push_str(&chunk.join(", "));
    }
    text.push_str("\n      ]");
    text
}

/// Build a packed struct initializer for a global with relocations.
///
/// LLVM cannot patch a 32-bit big-endian field inside a byte array constant, and
/// it rejects an aggregate-to-array `bitcast`. A packed struct of byte arrays and
/// `ptr` elements keeps every byte offset, lets LLVM write the relocated field
/// with the target's pointer width, and is a legal constant initializer. The
/// observable representation is still a byte image: opaque-pointer users reach
/// `@sym` with byte GEPs.
fn relocation_initializer(
    global: &Global,
    options: &Options,
) -> Result<(String, String), Diagnostic> {
    let size = global.bytes.len() as u64;
    // The IR relocation model records a 4-byte field for ShyISA. LLVM must write
    // a target pointer, so the byte image has to reserve the target pointer
    // width for the field; a mismatch is a frontend/layout error, not something
    // to paper over by overwriting neighbouring bytes.
    let width = options.layout.pointer_bytes as u64;
    let mut relocations: Vec<&Relocation> = global.relocations.iter().collect();
    relocations.sort_by_key(|relocation| relocation.offset);

    let mut field_types = Vec::new();
    let mut field_values = Vec::new();
    let mut cursor = 0u64;
    for relocation in relocations {
        let start = relocation.offset as u64;
        let end = start + width;
        if start < cursor {
            return Err(error(
                None,
                format!(
                    "global `{}`: relocation at offset {start} overlaps the previous field",
                    global.symbol
                ),
            ));
        }
        if end > size {
            return Err(error(
                None,
                format!(
                    "global `{}`: the relocated field at offset {start} needs {width} bytes for a \
                     target pointer, but the global image is only {size} bytes",
                    global.symbol
                ),
            ));
        }
        if global.bytes[start as usize..end as usize]
            .iter()
            .any(|byte| *byte != 0)
        {
            return Err(error(
                None,
                format!(
                    "global `{}`: the {width}-byte relocated field at offset {start} is not \
                     zeroed in the byte image",
                    global.symbol
                ),
            ));
        }
        if start > cursor {
            let bytes = &global.bytes[cursor as usize..start as usize];
            field_types.push(format!("[{} x i8]", bytes.len()));
            // Inside a struct body every element carries its own type, so the
            // array constant is spelled `[k x i8] [...]`, not bare `[...]`.
            field_values.push(format!("[{} x i8] {}", bytes.len(), byte_array(bytes)));
        }
        field_types.push("ptr".to_string());
        field_values.push(pointer_initializer(relocation));
        cursor = end;
    }
    if cursor < size {
        let bytes = &global.bytes[cursor as usize..];
        field_types.push(format!("[{} x i8]", bytes.len()));
        field_values.push(format!("[{} x i8] {}", bytes.len(), byte_array(bytes)));
    }

    Ok((
        format!("<{{ {} }}>", field_types.join(", ")),
        format!("<{{ {} }}>", field_values.join(", ")),
    ))
}

fn pointer_initializer(relocation: &Relocation) -> String {
    if relocation.addend == 0 {
        format!("ptr {}", symbol(&relocation.symbol))
    } else {
        format!(
            "ptr getelementptr (i8, ptr {}, i64 {})",
            symbol(&relocation.symbol),
            relocation.addend
        )
    }
}

// ---------------------------------------------------------------------------
// Declarations for symbols the module uses but does not define
// ---------------------------------------------------------------------------

struct DeclaredFunction {
    name: String,
    signature: Signature,
}

/// An unused-but-declared function is legal IR, but the backend only emits the
/// declarations the module actually needs.
struct ExternalSymbols<'a> {
    defined_functions: HashMap<&'a str, &'a Signature>,
    defined_globals: HashSet<&'a str>,
    functions: Vec<DeclaredFunction>,
    data: Vec<String>,
    memcpy: bool,
    memset: bool,
}

fn externals(module: &Module) -> Result<ExternalSymbols<'_>, Diagnostic> {
    let mut symbols = ExternalSymbols {
        defined_functions: module
            .functions
            .iter()
            .map(|function| (function.name.as_str(), &function.signature))
            .collect(),
        defined_globals: module
            .globals
            .iter()
            .map(|global| global.symbol.as_str())
            .collect(),
        functions: Vec::new(),
        data: Vec::new(),
        memcpy: false,
        memset: false,
    };
    for function in &module.functions {
        for (_, block) in function.live_blocks() {
            for inst in &block.insts {
                symbols.instruction(function, inst)?;
            }
        }
    }
    for global in &module.globals {
        for relocation in &global.relocations {
            symbols.reference(&relocation.symbol);
        }
    }
    Ok(symbols)
}

impl ExternalSymbols<'_> {
    fn instruction(&mut self, function: &Function, inst: &Inst) -> Result<(), Diagnostic> {
        match &inst.kind {
            InstKind::Call(call) => {
                let CallTarget::Direct(name) = &call.target else {
                    return Ok(());
                };
                if let Some(defined) = self.defined_functions.get(name.as_str()) {
                    if **defined != call.signature {
                        return Err(error(
                            inst.span,
                            format!(
                                "function `{}`: call to `{name}` uses signature `{}` but the \
                                 definition uses `{}`",
                                function.name, call.signature, defined
                            ),
                        ));
                    }
                    return Ok(());
                }
                if self.defined_globals.contains(name.as_str()) {
                    return Err(error(
                        inst.span,
                        format!(
                            "function `{}`: call target `{name}` is a global object, which LLVM \
                             IR cannot call",
                            function.name
                        ),
                    ));
                }
                self.declare_function(name, &call.signature, &function.name, inst.span)?;
            }
            InstKind::Load { address, .. } | InstKind::Store { address, .. } => {
                self.address(address);
            }
            InstKind::MemCpy { dst, src, .. } => {
                self.memcpy = true;
                self.address(dst);
                self.address(src);
            }
            InstKind::MemSet { dst, .. } => {
                self.memset = true;
                self.address(dst);
            }
            InstKind::SymbolAddr { symbol } => self.reference(symbol),
            InstKind::InlineAsm(asm) => {
                for binding in &asm.bindings {
                    self.address(&binding.address);
                }
            }
            _ => {}
        }
        Ok(())
    }

    fn address(&mut self, address: &Address) {
        if let AddressBase::Symbol(name) = &address.base {
            self.reference(name);
        }
    }

    fn reference(&mut self, name: &str) {
        if self.defined_functions.contains_key(name) || self.defined_globals.contains(name) {
            return;
        }
        if self.functions.iter().any(|function| function.name == name) {
            return;
        }
        if !self.data.iter().any(|symbol| symbol == name) {
            self.data.push(name.to_string());
        }
    }

    fn declare_function(
        &mut self,
        name: &str,
        signature: &Signature,
        caller: &str,
        span: Option<Span>,
    ) -> Result<(), Diagnostic> {
        if let Some(existing) = self.functions.iter().find(|function| function.name == name) {
            if existing.signature != *signature {
                return Err(error(
                    span,
                    format!(
                        "function `{caller}`: symbol `{name}` is called with conflicting \
                         signatures ({} and {})",
                        existing.signature, signature
                    ),
                ));
            }
            return Ok(());
        }
        self.data.retain(|symbol| symbol != name);
        self.functions.push(DeclaredFunction {
            name: name.to_string(),
            signature: signature.clone(),
        });
        Ok(())
    }

    fn is_empty(&self) -> bool {
        self.functions.is_empty() && self.data.is_empty() && !self.memcpy && !self.memset
    }

    fn emit(&self, w: &mut Writer, options: &Options) {
        let width = ptr_int_name(options.layout);
        if self.memcpy {
            w.line(format!(
                "declare void @llvm.memcpy.p0.p0.{width}(ptr, ptr, {width}, i1)"
            ));
        }
        if self.memset {
            w.line(format!(
                "declare void @llvm.memset.p0.{width}(ptr, i8, {width}, i1)"
            ));
        }
        if (self.memcpy || self.memset) && (!self.functions.is_empty() || !self.data.is_empty()) {
            w.blank();
        }
        for declared in &self.functions {
            w.line(declaration(declared));
        }
        if !self.functions.is_empty() && !self.data.is_empty() {
            w.blank();
        }
        for name in &self.data {
            w.line(format!("{} = external global [0 x i8]", symbol(name)));
        }
    }
}

fn declaration(declared: &DeclaredFunction) -> String {
    let mut text = format!(
        "declare {} {}(",
        ty(declared.signature.ret),
        symbol(&declared.name)
    );
    for (index, param) in declared.signature.params.iter().enumerate() {
        if index > 0 {
            text.push_str(", ");
        }
        text.push_str(&ty(*param));
    }
    if declared.signature.variadic {
        if !declared.signature.params.is_empty() {
            text.push_str(", ");
        }
        text.push_str("...");
    }
    text.push(')');
    text
}
