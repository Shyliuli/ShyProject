//! Textual LLVM IR backend for ShyC.
//!
//! This module turns the frozen typed CFG IR into LLVM assembly text. It is a
//! code generator, not a linker: the output is meant for `llc` or `clang -x ir`,
//! which own instruction selection, the ABI, and startup for the target triple.
//!
//! # Layout of the output
//!
//! Every global becomes a byte array; globals with relocations become packed
//! structs whose relocated field is a target-native `ptr` constant. Every
//! function becomes one `define`; calls to symbols the module does not define
//! become `declare`s. Aggregate values are emitted as `[size x i8]` blobs, so
//! their by-value calling convention is this compiler's own, not a C struct ABI.
//!
//! Two IR constructs cannot be represented and produce a
//! [`Diagnostic`](crate::source::Diagnostic) instead of bad code: inline
//! assembly (Shy-specific register bindings) and constructs LLVM rejects
//! outright (for example an entry block with predecessors and phi nodes).

