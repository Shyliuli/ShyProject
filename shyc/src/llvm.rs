/// What the backend needs to know about the target.
pub struct Options {
    /// LLVM target triple, emitted verbatim as `target triple`.
    pub triple: String,
    /// Pointer width and alignment used by the IR this module was built with.
    ///
    /// This should be [`Layout::LP64`] for a 64-bit triple. It selects the
    /// integer type used to materialize addresses, the width of a relocated
    /// global field, and the `llvm.memcpy`/`llvm.memset` length type.
    pub layout: Layout,
}

/// Render `module` as one complete LLVM IR assembly file.
///
/// The returned text always ends with a newline. Errors are returned only for
/// constructs LLVM cannot represent; every other IR instruction is emitted
/// one-to-one, without added attributes, fast-math flags, or `inbounds` claims.
pub fn emit(module: &Module, options: &Options) -> Result<String, Diagnostic> {
    let mut w = Writer::new();
    header(&mut w, module);
    w.line(format!(
        "target datalayout = \"{}\"",
        datalayout(&options.triple, options.layout)
    ));
    w.line(format!("target triple = \"{}\"", options.triple));
    w.blank();

    for global in &module.globals {
        emit_global(&mut w, global, options)?;
    }
    if !module.globals.is_empty() {
        w.blank();
    }

    let externals = externals(module)?;
    externals.emit(&mut w, options);
    if !externals.is_empty() {
        w.blank();
    }

    for (index, function) in module.functions.iter().enumerate() {
        if index > 0 {
            w.blank();
        }
        function::emit(&mut w, function, options)?;
    }

    Ok(w.out)
}

// ---------------------------------------------------------------------------
// Header and target layout
// ---------------------------------------------------------------------------

fn header(w: &mut Writer, module: &Module) {
    w.line("; Generated by ShyC (LLVM IR backend).");
    w.line(format!("; module: {}", comment_text(&module.name)));
    match &module.startup {
        Startup::Auto { entry, .. } if entry == "main" => {
            w.line("; startup: auto - the hosted C runtime starts the program and calls @main.");
        }
        Startup::Auto { entry, .. } => {
            w.line(format!(
                "; startup: auto entry=@{} - the C runtime starts at main, so provide a main",
                comment_text(entry)
            ));
            w.line(format!(
                "; wrapper or link with `-e {}`.",
                comment_text(entry)
            ));
        }
        Startup::Manual => {
            w.line("; startup: manual (#![no_main]) - link with -nostartfiles and provide _start;");
            w.line("; no Shy `setn sp` / `seta exit` sequence is emitted.");
        }
    }
    if module.resources.memory_bytes.is_some() || module.resources.stack_bytes.is_some() {
        w.line("; resources: ShyC memory/stack hints are not representable in LLVM IR; ignored.");
    }
    w.line("; aggregates are opaque `[N x i8]` blobs; by-value aggregate parameters and results");
    w.line("; use this backend's own convention, not a target C struct ABI.");
    if module
        .globals
        .iter()
        .any(|global| !global.relocations.is_empty())
    {
        w.line("; globals with relocations are packed structs; each relocated field is a `ptr`");
        w.line("; constant (`ptr @sym` plus an optional GEP addend) written in target order.");
    }
    w.line("; non-relocated global bytes are emitted verbatim; no byte-order conversion happens,");
    w.line("; so a big-endian ShyISA image is not valid little-endian target data.");
}

/// Keep a name from breaking out of the header comment.
fn comment_text(text: &str) -> String {
    text.replace(['\n', '\r'], " ")
}

/// A minimal data layout for the architectures this backend is used with.
///
/// Unknown triples fall back to a generic layout for the configured pointer
/// width; LLVM itself would also accept a module without a data layout.
fn datalayout(triple: &str, layout: Layout) -> &'static str {
    match triple.split('-').next().unwrap_or("") {
        "x86_64" => "e-m:e-p:64:64-i64:64-i128:128-n8:16:32:64-S128",
        "riscv64" | "loongarch64" | "aarch64" => "e-m:e-p:64:64-i64:64-i128:128-n32:64-S128",
        "i386" | "i486" | "i586" | "i686" | "riscv32" | "loongarch32" => {
            "e-m:e-p:32:32-i64:64-i128:128-n8:16:32-S128"
        }
        _ if layout.pointer_bytes <= 4 => "e-m:e-p:32:32-i64:64-i128:128-n8:16:32-S128",
        _ => "e-m:e-p:64:64-i64:64-i128:128-n8:16:32:64-S128",
    }
}

