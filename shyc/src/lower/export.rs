//! Explicit generic instance export: lowering side.
//!
//! The instance table is compile-time input. [`Lowerer::export_instances`]
//! resolves each entry through the ordinary instantiation cache, so an
//! instance the unit already uses is reused instead of compiled twice, and one
//! table entry that names no use still produces a concrete function.
//!
//! Requested functions are given a stable public C symbol. The concrete
//! symbol is the same for every alias of one instance, which is what makes
//! `Vec<int> as vec_int, Vec<int> as vint` one instantiation with two C names.
//! The alias names themselves are ordinary C wrappers generated by
//! `--emit=c-wrapper`, so the implementation keeps one symbol per concrete
//! function and the C boundary still gets a name per alias.
//!
//! A requested record exports its inherent methods: methods of a
//! materialized `impl<T> Vec<T>` and methods of a concrete `impl Vec<int>`
//! both belong to that instance, and a receiver method is the same function
//! the unit itself calls. Trait methods stay out of the table; a
//! trait-qualified entry is rejected by the table parser instead of being
//! half-exported.

use std::collections::{HashMap, HashSet};

use crate::ast;
use crate::export_instances::{CTypeName, ExportedInstance, ExportedKind, ExportedMethod};
use crate::sema::types::{RecordKind, TypeId, TypeKind};
use crate::source::{Diagnostic, Span};

use super::{ExportRequest, Lowerer};

impl Lowerer {
    /// Instantiates every requested instance and publishes its C symbols.
    ///
    /// Runs after the collection pass, so file-scope types and templates all
    /// exist, and before body lowering, so the bodies that call an instance
    /// see the exported symbol.
    pub(super) fn export_instances(
        &mut self,
        requests: &[ExportRequest],
    ) -> Result<Vec<ExportedInstance>, Diagnostic> {
        let mut exports = Vec::with_capacity(requests.len());
        for request in requests {
            exports.push(self.export_instance(request)?);
        }
        Ok(exports)
    }

    fn export_instance(&mut self, request: &ExportRequest) -> Result<ExportedInstance, Diagnostic> {
        let name = request.name.text.as_str();
        if !self.generic_functions.contains_key(name)
            && !self.generic_records.contains_key(name)
            && !self.generic_enums.contains_key(name)
        {
            return Err(Diagnostic::new(
                request.name.span,
                format!(
                    "'{name}' is not a generic template; the instance table lists only generic \
                     records, enums, and functions"
                ),
            ));
        }
        // A record name and a function name live in different namespaces, and
        // a generic function is the only template that has no concrete type of
        // its own to instantiate.
        if self.generic_functions.contains_key(name) {
            let instance = self.instantiate_generic_function(&request.name, &request.args)?;
            self.reject_variadic(
                instance.ty,
                &format!("'{}'", request.name.text),
                request.name.span,
            )?;
            let desired = self.published_function_symbol(&instance.symbol);
            let symbol = self.publish_symbol(&instance.symbol, &desired);
            return Ok(ExportedInstance {
                alias: request.alias.clone(),
                kind: ExportedKind::Function {
                    ty: instance.ty,
                    symbol,
                },
            });
        }
        let ty = self.instantiate_generic(&request.name, &request.args, request.name.span)?;
        match self.types.kind(ty) {
            TypeKind::Record { .. } => {
                self.instantiate_generic_impl(ty)?;
                let methods = self.export_record_methods(ty, request.name.span)?;
                Ok(ExportedInstance {
                    alias: request.alias.clone(),
                    kind: ExportedKind::Record { ty, methods },
                })
            }
            TypeKind::Enum(_) | TypeKind::PayloadEnum(_) => Ok(ExportedInstance {
                alias: request.alias.clone(),
                kind: ExportedKind::Enum { ty },
            }),
            _ => Err(Diagnostic::new(
                request.name.span,
                format!("'{name}<...>' did not resolve to a record, enum, or function"),
            )),
        }
    }

    /// Exports every ordinary inherent method of one concrete record.
    fn export_record_methods(
        &mut self,
        record: TypeId,
        span: Span,
    ) -> Result<Vec<ExportedMethod>, Diagnostic> {
        let Some(info) = self.impls.get(&record) else {
            return Ok(Vec::new());
        };
        let mut names: Vec<String> = info.methods.keys().cloned().collect();
        names.sort();
        let mut generic_methods: Vec<String> = info.generic_methods.keys().cloned().collect();
        generic_methods.sort();
        // A method with its own type parameters has no single C signature, and
        // the table has no syntax to name one instantiation of it.
        if let Some(method) = generic_methods.first() {
            return Err(Diagnostic::new(
                span,
                format!(
                    "generic method '{method}' declares its own type parameters, so it cannot be \
                     exported as '<alias>_<method>'; export a record whose inherent impl has only \
                     ordinary methods"
                ),
            ));
        }
        let mut methods = Vec::new();
        for name in names {
            let method_name = ast::Name::new(name.clone(), span);
            let Some(method) = self.method_of(record, &method_name)? else {
                continue;
            };
            self.reject_variadic(method.ty, &format!("method '{name}'"), span)?;
            let desired = self.published_method_symbol(record, &name);
            let symbol = self.publish_symbol(&method.symbol, &desired);
            methods.push(ExportedMethod {
                name,
                ty: method.ty,
                symbol,
            });
        }
        Ok(methods)
    }

    /// A C wrapper cannot forward a variadic argument list.
    fn reject_variadic(&self, ty: TypeId, what: &str, span: Span) -> Result<(), Diagnostic> {
        if let TypeKind::Function { variadic: true, .. } = self.types.kind(ty) {
            return Err(Diagnostic::new(
                span,
                format!("{what} is variadic and cannot be exported as a C wrapper"),
            ));
        }
        Ok(())
    }

    /// Renames a concrete instance symbol to a public C symbol.
    ///
    /// The same instance may be requested under several aliases; the first
    /// request renames, and the later ones find the already published symbol.
    fn publish_symbol(&mut self, current: &str, desired: &str) -> String {
        if current == desired {
            return desired.to_string();
        }
        // A concrete `impl Vec<int>` method already has a public symbol; the
        // wrapper calls it as it is.
        if !current.starts_with(".L.") {
            return current.to_string();
        }
        for pending in &mut self.pending {
            if pending.symbol == current {
                pending.symbol = desired.to_string();
                pending.internal = false;
            }
        }
        for instance in self.function_instances.values_mut() {
            if instance.symbol == current {
                instance.symbol = desired.to_string();
            }
        }
        for implementation in self.impls.values_mut() {
            for method in implementation.methods.values_mut() {
                if method.symbol == current {
                    method.symbol = desired.to_string();
                }
            }
            for methods in implementation.trait_methods.values_mut() {
                for method in methods.methods.values_mut() {
                    if method.symbol == current {
                        method.symbol = desired.to_string();
                    }
                }
            }
        }
        for method in self.from_conversions.values_mut() {
            if method.symbol == current {
                method.symbol = desired.to_string();
            }
        }
        for global in &mut self.module.globals {
            for relocation in &mut global.relocations {
                if relocation.symbol == current {
                    relocation.symbol = desired.to_string();
                }
            }
        }
        desired.to_string()
    }

    /// The public symbol of one generic function instance.
    ///
    /// The instance key already names the template and its concrete
    /// arguments, so the mangling is stable for one source file and cannot
    /// collide with another instance.
    fn published_function_symbol(&self, current: &str) -> String {
        let Some((key, _)) = self
            .function_instances
            .iter()
            .find(|(_, instance)| instance.symbol == current)
        else {
            return format!("shyc_inst_fn_{}", Self::sanitize_ident(current));
        };
        let mut symbol = format!(
            "shyc_inst_{}_fn_{}",
            self.module_prefix,
            Self::sanitize_ident(&key.name)
        );
        push_argument_mangling(&mut symbol, &key.args);
        symbol
    }

    /// The public symbol of one inherent method of a concrete record.
    fn published_method_symbol(&self, record: TypeId, method: &str) -> String {
        format!(
            "shyc_inst_{}_m_r{}_{}",
            self.module_prefix,
            record.index(),
            Self::sanitize_ident(method)
        )
    }

    // -----------------------------------------------------------------------
    // C type names
    // -----------------------------------------------------------------------

    /// Collects the C spelling of every record and enum type an export can
    /// mention.
    ///
    /// The C printer never derives a name from an arena index on its own: a
    /// plain record already has a C name in the input file, and a generic
    /// instance gets a deterministic synthesized name. Both the header and the
    /// wrapper use this one map, so their declarations agree.
    pub(super) fn c_type_names(&self, exports: &[ExportedInstance]) -> HashMap<TypeId, CTypeName> {
        let mut names = HashMap::new();
        let mut work: Vec<TypeId> = Vec::new();
        for export in exports {
            match &export.kind {
                ExportedKind::Record { ty, methods } => {
                    work.push(*ty);
                    for method in methods {
                        work.push(method.ty);
                    }
                }
                ExportedKind::Enum { ty } | ExportedKind::Function { ty, .. } => work.push(*ty),
            }
        }
        while let Some(ty) = work.pop() {
            if names.contains_key(&ty) {
                continue;
            }
            if let Some(name) = self.c_type_name(ty) {
                names.insert(ty, name);
            }
            match self.types.kind(ty) {
                TypeKind::Record { .. } => {
                    if let Some(info) = self.types.record_info(ty) {
                        for field in &info.fields {
                            work.push(field.ty.ty);
                        }
                    }
                }
                TypeKind::PayloadEnum(_) | TypeKind::Enum(_) => {
                    if let Some(info) = self.types.enum_info(ty) {
                        work.push(info.underlying);
                        for variant in &info.variants {
                            if let Some(payload) = variant.payload {
                                work.push(payload);
                            }
                        }
                    }
                }
                TypeKind::Pointer { pointee } => work.push(pointee.ty),
                TypeKind::Array { element, .. } => work.push(element.ty),
                TypeKind::Function { result, params, .. } => {
                    work.push(*result);
                    work.extend(params.iter().copied());
                }
                _ => {}
            }
        }
        names
    }

    /// Whether a plain record's definition mentions a generic instance, which
    /// makes the ordinary AST header skip it.
    fn record_mentions_instance(&self, ty: TypeId) -> bool {
        let mut visited = HashSet::new();
        self.record_is_tainted(ty, &mut visited)
    }

    fn record_is_tainted(&self, ty: TypeId, visited: &mut HashSet<TypeId>) -> bool {
        if self.record_instance_key(ty).is_some() {
            return true;
        }
        if !visited.insert(ty) {
            return false;
        }
        self.types.record_info(ty).is_some_and(|info| {
            info.fields
                .iter()
                .any(|field| self.type_is_tainted(field.ty.ty, visited))
        })
    }

    fn type_is_tainted(&self, ty: TypeId, visited: &mut HashSet<TypeId>) -> bool {
        match self.types.kind(ty) {
            TypeKind::Record { .. } => self.record_is_tainted(ty, visited),
            TypeKind::Enum(_) | TypeKind::PayloadEnum(_) => {
                self.enum_instances.values().any(|instance| *instance == ty)
                    || self.types.enum_info(ty).is_some_and(|info| {
                        info.variants.iter().any(|variant| {
                            variant
                                .payload
                                .is_some_and(|payload| self.type_is_tainted(payload, visited))
                        })
                    })
            }
            TypeKind::Pointer { pointee } => self.type_is_tainted(pointee.ty, visited),
            TypeKind::Array { element, .. } => self.type_is_tainted(element.ty, visited),
            TypeKind::Function { result, params, .. } => {
                self.type_is_tainted(*result, visited)
                    || params
                        .iter()
                        .any(|param| self.type_is_tainted(*param, visited))
            }
            _ => false,
        }
    }

    /// The C spelling of one concrete type, when it is a record or enum.
    fn c_type_name(&self, ty: TypeId) -> Option<CTypeName> {
        // `Result<void, E>` 的 niche 用 `E` 的整数值（0 = Ok）表示，C 这边
        // 直接沿用底层类型的拼写，既没有 tag 也没有 payload union。
        if let TypeKind::PayloadEnum(_) = self.types.kind(ty) {
            if let Some(info) = self.types.enum_info(ty) {
                if info.niche {
                    let base = self
                        .c_type_name(info.underlying)
                        .map(|name| name.base)
                        .unwrap_or_else(|| "int".to_string());
                    return Some(CTypeName {
                        base,
                        emit_header: false,
                    });
                }
            }
        }
        let scope = self.type_scopes.first()?;
        match self.types.kind(ty) {
            TypeKind::Record { kind, .. } => {
                let keyword = match kind {
                    RecordKind::Struct => "struct",
                    RecordKind::Union => "union",
                };
                // A trait used as a value is the function-pointer record the
                // ordinary header prints under the trait's own name; use that
                // name so a C caller can pass its `Drawable` value unchanged.
                if let Some(name) = self
                    .trait_values
                    .iter()
                    .find_map(|(name, value)| (*value == ty).then_some(name.clone()))
                {
                    return Some(CTypeName {
                        base: name,
                        emit_header: false,
                    });
                }
                // A generic instance is not spelled in C, and a plain record
                // may have a typedef name that the ordinary header already
                // prints.
                if self.record_instance_key(ty).is_some() {
                    return Some(CTypeName {
                        base: format!("{keyword} shyc_R{}", ty.index()),
                        emit_header: true,
                    });
                }
                // A plain record whose members mention a generic instance is
                // not printed by the ordinary AST export, because C cannot
                // spell it there. The instance section prints it instead, so
                // an exported signature never names an unknown type.
                let emit_header = self.record_mentions_instance(ty);
                if let Some(name) = first_name(&scope.typedefs, ty) {
                    return Some(CTypeName {
                        base: name,
                        emit_header,
                    });
                }
                if let Some(tag) = first_name(&scope.tags, ty) {
                    return Some(CTypeName {
                        base: format!("{keyword} {tag}"),
                        emit_header,
                    });
                }
                Some(CTypeName {
                    base: format!("{keyword} shyc_R{}", ty.index()),
                    emit_header: true,
                })
            }
            // Every enum is spelled by a synthesized integer typedef or a
            // tag+payload structure, so its width is exact even for
            // `enum(u8)`; a plain C `enum` spelling would let the C compiler
            // choose a different width.
            TypeKind::PayloadEnum(_) => Some(CTypeName {
                base: format!("struct shyc_E{}", ty.index()),
                emit_header: true,
            }),
            TypeKind::Enum(_) => Some(CTypeName {
                base: format!("shyc_E{}", ty.index()),
                emit_header: true,
            }),
            _ => None,
        }
    }
}

/// The lexicographically first name mapping to `ty`, so header and wrapper
/// invocations pick the same spelling.
fn first_name(names: &HashMap<String, TypeId>, ty: TypeId) -> Option<String> {
    let mut matching: Vec<&String> = names
        .iter()
        .filter(|(_, declared)| **declared == ty)
        .map(|(name, _)| name)
        .collect();
    matching.sort();
    matching.first().map(|name| (*name).clone())
}

/// Appends one `_t<id>` or `_n<bits>` part per concrete argument.
fn push_argument_mangling(symbol: &mut String, args: &[super::GenericArgKey]) {
    for argument in args {
        match argument {
            super::GenericArgKey::Type(ty) => {
                symbol.push_str(&format!("_t{}", ty.index()));
            }
            super::GenericArgKey::Int(value) => {
                symbol.push_str(&format!("_n{:016x}", *value as u64));
            }
        }
    }
}
